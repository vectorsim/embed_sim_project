/**
 * \brief Configures TMADC0 channel 2 for Vdc on AN2.
 * \details
 */
void CddAdc_Init_TMADC0_CH2_An2_Vdc(void)
{
    Ifx_ADC_TMADC_CH_CFG   chCFG;
    Ifx_ADC_TMADC_BND_SEL  bndSel;
    Ifx_ADC_TMADC_RSLT_CFG rsltCfg;
    Ifx_ADC_TMADC_BFL_CFG  bflCfg;

    chCFG.U = ADC_TMADC0_CH2_CFG.U;
    ADC_TMADC0_MODCFG.B.RUN = 0x0U;

    /* --- Channel Config   --- */
    ADC_TMADC0_CH2_STC.B.ST = CDD_ADC_PHASE_SAMPLE_TICKS;
    ADC_TMADC0_CMATCFG.B.CHCSEL |= (1u << 2);

    chCFG.B.TSEN    = 0u;
    chCFG.B.RSEL    = 2u;
    chCFG.B.ATREN   = 0u;
    chCFG.B.HWTR0MS = CDD_ADC_HWTRIG_MUX;
    chCFG.B.HWTR0M  = CDD_ADC_HWTRIG_EDGE_FALLING;
    ADC_TMADC0_CH2_CFG.U = chCFG.U;


    /* *** Route BFL0 onto the eGTM boundary-flag bus (cluster 0) *** */
    /* The 6-bit code selects which ADC BFL is driven.  On TC4D7,
       TMADC0.BFL0 is index 0, so write OUT0SEL = 0.               */
    ADC_ETBF0SEL.B.OUT0SEL = 0u;

    ADC_TMADC0_MODCFG.B.RUN = 1u;
}

