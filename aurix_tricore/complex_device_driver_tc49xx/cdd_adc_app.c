/**********************************************************************************************************************
 * \file      cdd_adc_app.c
 * \brief     TMADC application module (three phases + Vdc).
 *
 * \details
 *   Phase U : AN1   (X2.26)               -> TMADC0.Ch1 -> AW0_RES1
 *   Phase V : AN16  (Shield2Go #1 pin 2)  -> TMADC1.Ch4 -> AW0_RES4
 *   Phase W : P00.3 (Arduino A2 / X301.3) -> TMADC2.Ch9 -> AW0_RES9
 *   Vdc     : AN2   (X2.25)               -> TMADC0.Ch2 -> AW0_RES2
 *
 *   AN1, AN16 and AN2 are class-D dedicated analog inputs (no GPIO overlay).
 *   P00.3 is a SLOW pad with GPIO overlay and is configured through
 *   CddGpio_ConfigAdc_Tmadc2_Ch9_P00_03_PhaseW().
 *
 *   All four channels are triggered by the same eGTM_CLS0 hardware trigger
 *   generated by ATOM0 CH1 (HWTR0MS = 36, rising edge).
 *
 * \note      TC4D7 has no DSADC block (datasheet: DS Converters = 0).
 *
 * \version   1.0.3
 * \date      2026-10-12
 * \copyright Copyright (C) EmbedSim Project / Paul Abraham 2024
 *            SPDX-License-Identifier: MIT
 *********************************************************************************************************************/

