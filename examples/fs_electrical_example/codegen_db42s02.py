"""
codegen_db42s02.py
==================
Project-local C_CUSTOM_EMIT overrides for the DB42S02 open-loop chain.

Rule: This is the ONE file in this project allowed to contain C strings.
      The three blocks below have non-standard C signatures that cannot
      be auto-generated by PYXInspector — they require C_CUSTOM_EMIT.
      Everything else in the chain is auto-emitted.

Import once from db42s02_openloop_fmu.py (after block classes are available):

    import codegen_db42s02

No base class.  No inheritance.  Pure attribute patching.
"""

from coordinate_transform_blocks import InvParkTransformBlock
from svpwm_block                 import SVPWMBlock
from motor_utility_blocks        import SVPWMPackBlock

# Motor constant — DB42S02 only
V_DC = 17.0


# =============================================================================
# InvParkTransformBlock
# Non-standard signature: individual scalar args + pointer-out, not flat u[].
# =============================================================================
InvParkTransformBlock.C_CUSTOM_EMIT = "\n".join([
    "    /* --- inv_park (InvParkTransformBlock) --- */",
    "    real32_T y_inv_park[2];",
    "    {",
    "        MatrixFloat invpark_alpha, invpark_beta;",
    "        InvPark_Step(&inv_park_state,",
    "                     y_vf_dq[0],      /* v_d     */",
    "                     y_vf_dq[1],      /* v_q     */",
    "                     y_vf_theta[0],   /* theta_e */",
    "                     &invpark_alpha,",
    "                     &invpark_beta);",
    "        y_inv_park[0] = (real32_T)invpark_alpha;",
    "        y_inv_park[1] = (real32_T)invpark_beta;",
    "    }",
])


# =============================================================================
# SVPWMPackBlock
# Inline polar conversion — sqrtf / atan2f + compile-time V_dc constant.
# =============================================================================
SVPWMPackBlock.C_CUSTOM_EMIT = "\n".join([
    "    /* --- svpwm_pack (SVPWMPackBlock) — inline polar conversion --- */",
    "    real32_T y_svpwm_pack[3];",
    "    y_svpwm_pack[0] = sqrtf(  y_inv_park[0] * y_inv_park[0]",
    "                            + y_inv_park[1] * y_inv_park[1]);",
    "    y_svpwm_pack[1] = atan2f( y_inv_park[1], y_inv_park[0]);",
   f"    y_svpwm_pack[2] = {V_DC:.4f}f;   /* V_dc */",
])


# =============================================================================
# SVPWMBlock
# Struct-based I/O — SVPWM_Input / SVPWM_Output, reads y_svpwm_pack[].
# =============================================================================
SVPWMBlock.C_CUSTOM_EMIT = "\n".join([
    "    /* --- svpwm (SVPWMBlock) — struct-based I/O --- */",
    "    real32_T y_svpwm[4];",
    "    {",
    "        SVPWM_Input  svpwm_in;",
    "        SVPWM_Output svpwm_out;",
    "        svpwm_in.Vref  = y_svpwm_pack[0];   /* Vref  */",
    "        svpwm_in.alpha = y_svpwm_pack[1];   /* alpha */",
    "        svpwm_in.Vdc   = y_svpwm_pack[2];   /* V_dc  */",
    "        svpwm_in.Ts    = dt;",
    "        SVPWM_Step(&svpwm_in, &svpwm_out);",
    "        y_svpwm[0] = svpwm_out.T1;",
    "        y_svpwm[1] = svpwm_out.T2;",
    "        y_svpwm[2] = svpwm_out.T0;",
    "        y_svpwm[3] = (real32_T)svpwm_out.sector;",
    "    }",
])
