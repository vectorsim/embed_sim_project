#ifndef DEBUG_H_
#define DEBUG_H_

/*********************************************************************************************************************/
/*-----------------------------------------------------Includes------------------------------------------------------*/
/*********************************************************************************************************************/
#include "Ifx_Types.h"

/*********************************************************************************************************************/
/*-------------------------------------------------Data Structures---------------------------------------------------*/
/*********************************************************************************************************************/
/**
 * \brief Data structure for debug utilities.
 * \details
 * This structure is used to store debug-related flags and parameters for
 * controlling and monitoring motor operation in PMSM motor control systems.
 */
typedef struct {
    boolean startStop;            /**< \brief Flag to start or stop the motor:
                                       - `TRUE`: Start the motor.
                                       - `FALSE`: Stop the motor. */
    boolean startCalibration;     /**< \brief Flag to initiate motor calibration:
                                       - `TRUE`: Start calibration.
                                       - `FALSE`: Do not start calibration. */
    boolean direction;            /**< \brief Motor rotation direction:
                                       - `TRUE`: Forward direction.
                                       - `FALSE`: Reverse direction. */
    float32 targetSpeedRpm;       /**< \brief Target speed for the motor in RPM. */
} Debug;

#endif /* DEBUG_H_ */
