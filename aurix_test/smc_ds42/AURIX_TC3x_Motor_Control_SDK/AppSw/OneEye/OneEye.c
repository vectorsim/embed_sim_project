extern MotorControl        g_motorControl;                 /**< Motor control instance. */

/*********************************************************************************************************************/
/*-------------------------------------------------Global variables--------------------------------------------------*/
/*********************************************************************************************************************/
Ifx_Oe_Osci         g_dasOsci;                      /**< Oscilloscope instance. */
Ifx_Oe_DasPipe      g_oneEyeDasPipe;                /**< OneEye data pipe instance. */
IfxStdIf_DPipe      g_dPipe;                        /**< Standardized command pipe. */
Ifx_Shell           g_shell;                        /**< Shell command processing instance. */

/*--------------------------------------------------------------------------------------------------
 * Shell Command Configuration
 *------------------------------------------------------------------------------------------------*/
/** \brief Array of shell commands supported by the motor control system. */
const Ifx_Shell_Command g_shellCommands[] = {
    {"help", SHELL_HELP_DESCRIPTION_TEXT, &g_shell, &Ifx_Shell_showHelp},
    {"info", "     : Dummy info command", &g_shell, &printShellInfo},
    {"set ecu run 1", "     : Start motor command", &g_shell, &shellCmdSetEcuStart},
    {"set ecu run 0", "     : Stop motor command", &g_shell, &shellCmdSetEcuStop},
    {"set ecu cal 1", "     : Calibrate motor command", &g_shell, &shellCmdSetEcuCal},
    IFX_SHELL_COMMAND_LIST_END
};
