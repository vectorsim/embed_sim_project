boolean printShellInfo(pchar args, void *data, IfxStdIf_DPipe *io)
{
    IfxStdIf_DPipe_print(io, "The shell info command was called !" ENDL);
    return TRUE;
}

boolean shellCmdSetEcuStart(pchar args, void *data, IfxStdIf_DPipe *io)
{
    PmsmFoc_Interface_startMotor(&g_motorControl,TRUE);
    IfxStdIf_DPipe_print(io, "The shell start motor command was called !" ENDL);
    return TRUE;
}

boolean shellCmdSetEcuStop(pchar args, void *data, IfxStdIf_DPipe *io)
{
    PmsmFoc_Interface_stopMotor(&g_motorControl,TRUE);
    IfxStdIf_DPipe_print(io, "The shell start motor command was called !" ENDL);
    return TRUE;
}

boolean shellCmdSetEcuCal(pchar args, void *data, IfxStdIf_DPipe *io)
{
    if(g_motorControl.controlParameters.state == StateMachine_motorStop)
    {
        PmsmFoc_PhaseCurrentSense_resetCalibrationStatus(&g_motorControl.inverter.phaseCurrentSense);
        PmsmFoc_resetEncoderCalibrationStatus(&g_motorControl);
        PmsmFoc_PositionAcquisition_init(&g_motorControl.positionSensor, PositionAcquisition_SensorType_Encoder);
        PmsmFoc_Interface_startMotor(&g_motorControl,TRUE);
    }
    IfxStdIf_DPipe_print(io, "The shell calibrate motor command was called !" ENDL);
    return TRUE;
}

void OneEye_initOneEye(void)
{
    /* Initialize Ifx_OneEyeDasPipe to enable data streaming between the controller and OneEye */
    Ifx_Oe_DasPipe_Config pipeCfg;

    Ifx_Oe_DasPipe_initConfig(&pipeCfg);
    pipeCfg.size = 1024; /* Ifx_OneEyeDasPipe requires twice the size in the heap (rx and tx). Maximum size is 1024 i.e. 2kB heap. */

    Ifx_Oe_DasPipe_init(&g_oneEyeDasPipe, &pipeCfg);

    /* Initialize IfxStdIf_DPipe with the Ifx_OneEyeDasPipe */
    Ifx_Oe_DasPipe_stdIfDPipeInit(&g_dPipe, &g_oneEyeDasPipe);

    /* Print something directly into the pipe */
    IfxStdIf_DPipe_print(&g_dPipe, "Hello World !" ENDL);
    IfxStdIf_DPipe_print(&g_dPipe, "Enter 'help' to see the command list !" ENDL);

    /* Initialize the shell */
    Ifx_Shell_Config shellConf;
    Ifx_Shell_initConfig(&shellConf);                       /* Initialize the structure with default values         */

    shellConf.standardIo = &g_dPipe;                        /* Set a pointer to the standard interface              */
    shellConf.commandList[0] = &g_shellCommands[0];         /* Set the supported command list                       */

    /* Apply the configuration to the shell */
    Ifx_Shell_init(&g_shell, &shellConf);                   /* Initialize the Shell with the given configuration    */

    /* Oscilloscope configuration structure */
    Ifx_Oe_Osci_Config osciCfg;

    /* Oscilloscope configuration structure initialization */
    Ifx_Oe_Osci_initConfig(&osciCfg);

    {
        /* When a signal is created, automatically assign the signal to a channel if there is a free channel */
        osciCfg.autoAddChannels = TRUE;
        /* Only used for FFT, but it doesn't hurt to configure it */
        osciCfg.samplePeriod = 50e-6;
        /* Mode of the osci after initialization (can be changed at runtime) */
        osciCfg.triggerMode = Ifx_Oe_Osci_TriggerMode_automatic;
    }
    /* Call the oscilloscope initialization function */
    Ifx_Oe_Osci_init(&g_dasOsci, &osciCfg);

    /* Add the oscilloscope signals */
    Ifx_Oe_Osci_addSignal(&g_dasOsci, "Ialpha [A]", Ifx_Oe_Osci_DataType_Float32, &g_motorControl.pmsmFoc.iab.real, 0);
    Ifx_Oe_Osci_addSignal(&g_dasOsci, "Ibeta [A]", Ifx_Oe_Osci_DataType_Float32, &g_motorControl.pmsmFoc.iab.imag, 0);
    Ifx_Oe_Osci_addSignal(&g_dasOsci, "Valpha [p.u]", Ifx_Oe_Osci_DataType_Float32, &g_motorControl.pmsmFoc.vabRef.real, 0);
    Ifx_Oe_Osci_addSignal(&g_dasOsci, "Vbeta [p.u]", Ifx_Oe_Osci_DataType_Float32, &g_motorControl.pmsmFoc.vabRef.imag, 0);
    Ifx_Oe_Osci_addSignal(&g_dasOsci, "ElPos [dig]", Ifx_Oe_Osci_DataType_SInt16, &g_motorControl.pmsmFoc.electricalAngle, 0);
    Ifx_Oe_Osci_addSignal(&g_dasOsci, "Iu [A]", Ifx_Oe_Osci_DataType_Float32, &g_motorControl.pmsmFoc.iPhaseMeas.u, 0);
    Ifx_Oe_Osci_addSignal(&g_dasOsci, "Iv [A]", Ifx_Oe_Osci_DataType_Float32, &g_motorControl.pmsmFoc.iPhaseMeas.v, 0);
    Ifx_Oe_Osci_addSignal(&g_dasOsci, "Iw [A]", Ifx_Oe_Osci_DataType_Float32, &g_motorControl.pmsmFoc.iPhaseMeas.w, 0);

    /* Call the oscilloscope start function */
    Ifx_Oe_Osci_start(&g_dasOsci);
}
