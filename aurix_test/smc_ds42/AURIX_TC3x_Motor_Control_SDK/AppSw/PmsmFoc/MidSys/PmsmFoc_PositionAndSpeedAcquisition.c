void PmsmFoc_PositionAcquisition_init(PositionAcquisition* positionAcquisition, PositionAcquisition_SensorType sensorType)
{

	positionAcquisition->statusOk = TRUE;
    switch(sensorType)
    {
        case PositionAcquisition_SensorType_Hall:
        {
            /* Not implemented*/
            break;
        }
        case PositionAcquisition_SensorType_Encoder:
        {
            PmsmFoc_Gpt12_initGpt12(&positionAcquisition->encoder.incrEncoder);
            break;
        }
        case PositionAcquisition_SensorType_Resolver:
        {
        	/* Not implemented*/
            break;
        }
        case PositionAcquisition_SensorType_Sensorless:
        {
            /* Not implemented*/
            break;
        }
        case PositionAcquisition_SensorType_Encoder_and_Resolver:
        {
        	/* Not implemented*/
            break;
        }
        default:
        {
        	positionAcquisition->statusOk= FALSE;
            break;
        }
    }

    {
        Ifx_LowPassPt1F32_Config lpfConfig;
        lpfConfig.gain            = 1.0;
        lpfConfig.cutOffFrequency = 1000;
        lpfConfig.samplingTime    = (1/((float32)USER_INVERTER_PWM_FREQ_HZ));
        Ifx_LowPassPt1F32_init(&positionAcquisition->speedLpf, &lpfConfig);
    }
}

sint32 PmsmFoc_PositionAcquisition_updatePosition(PositionAcquisition* positionAcquisition)
{
	sint32 position = 0;
	switch(positionAcquisition->sensorType)
	    {
	        case PositionAcquisition_SensorType_Hall:
	        {
	            /* Not implemented*/
	            break;
	        }
	        case PositionAcquisition_SensorType_Encoder:
	        {
	            sint32 rawPosition;
	            IfxGpt12_IncrEnc *encoder= &positionAcquisition->encoder.incrEncoder;

	            IfxGpt12_IncrEnc_update(encoder);
	            rawPosition= IfxGpt12_IncrEnc_getRawPosition(encoder);
	            position= ((rawPosition * (uint32)USER_MOTOR_POLE_PAIR * (uint32)COSSIN_TABLE_SIZE) / encoder->resolution) & (uint32)(COSSIN_TABLE_SIZE-1);
	            break;
	        }
	        case PositionAcquisition_SensorType_Resolver:
	        {
	        	/* Not implemented*/
	        	break;
	        }
	        case PositionAcquisition_SensorType_Encoder_and_Resolver:
	        {
	        	/* Not implemented*/
	        	break;
	        }
	        case PositionAcquisition_SensorType_Sensorless:
	        {
	            /* Not implemented*/
	            break;
	        }
	        default: break;
	    }
	    return(position);
}

void PmsmFoc_PositionAcquisition_updateSpeed(PositionAcquisition* positionAcquisition)
{
	float32 speed = 0.0f;

	    switch(positionAcquisition->sensorType)
	    {
	        case PositionAcquisition_SensorType_Hall:
	        {
	            /* Not implemented*/
	            break;
	        }
	        case PositionAcquisition_SensorType_Encoder:
	        {
	            speed= IfxGpt12_IncrEnc_getSpeed(&positionAcquisition->encoder.incrEncoder);
	            break;
	        }
	        case PositionAcquisition_SensorType_Resolver:
	        	/* Not implemented*/
	        	break;
	        case PositionAcquisition_SensorType_Encoder_and_Resolver:
	        {
	        	/* Not implemented*/
	        	break;
	        }
	        case PositionAcquisition_SensorType_Sensorless:
	        {
	            /* Not implemented*/
	            break;
	        }
	        default: break;
	    }

	    positionAcquisition->rotorSpeed = Ifx_LowPassPt1F32_do(&positionAcquisition->speedLpf, speed);
}

float32 PmsmFoc_PositionAcquisition_getSpeed(PositionAcquisition* positionAcquisition)
{
    return positionAcquisition->rotorSpeed;
}
