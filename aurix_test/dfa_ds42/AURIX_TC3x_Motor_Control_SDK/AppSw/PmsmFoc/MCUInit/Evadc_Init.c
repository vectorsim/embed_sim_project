/**
 * \brief Initialize the EVADC module and its associated channels.
 * \details
 * This function initializes the EVADC module, its groups, and its channels for current
 * sensing, BEMF voltage measurement, and DC link voltage monitoring in PMSM motor control.
 *
 * \param[in] inverter Pointer to the inverter structure containing configuration data.
 */
void PmsmFoc_Evadc_initEvadc(Inverter *const inverter)
{
    PmsmFoc_Evadc_initModule();
    PmsmFoc_Evadc_initGroups();

    PmsmFoc_Evadc_initCurrentSenseChannels(inverter);

#if (BEMF_MEASUREMENT == ENABLED)
    PmsmFoc_Evadc_initBemfVoltageSenseChannels(inverter);
#endif

#if (DC_LINK_VOLTAGE_MEASUREMENT == ENABLED)
    PmsmFoc_Evadc_initDcLinkVoltageSenseChannels(inverter);
#endif
}
