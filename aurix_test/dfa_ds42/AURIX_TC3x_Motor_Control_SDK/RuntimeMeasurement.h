/**
 * \brief Structure to hold runtime measurement data.
 * \details
 * This structure stores performance counter values and calculates runtime metrics,
 * including the current runtime, maximum runtime, and minimum runtime.
 */
typedef struct
{
    float32 runTime;          /**< \brief Current runtime in seconds. */
    float32 runTimeMax;       /**< \brief Maximum runtime recorded. */
    float32 runTimeMin;       /**< \brief Minimum runtime recorded. */
    IfxCpu_Perf PerfCounters; /**< \brief CPU performance counters used for runtime measurement. */
} RuntimeMeasurement;

