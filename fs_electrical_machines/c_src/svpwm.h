/** \addtogroup svpwm_enums
 * \{ */

/**
 * \enum SVM_Sector_Type
 * \brief SVM sectors (I through VI)
 */
typedef enum
{
    SVM_SECTOR_I = 0U,     /**< Sector I: 0° to 60° */
    SVM_SECTOR_II = 1U,    /**< Sector II: 60° to 120° */
    SVM_SECTOR_III = 2U,   /**< Sector III: 120° to 180° */
    SVM_SECTOR_IV = 3U,    /**< Sector IV: 180° to 240° */
    SVM_SECTOR_V = 4U,     /**< Sector V: 240° to 300° */
    SVM_SECTOR_VI = 5U     /**< Sector VI: 300° to 360° */
} SVM_Sector_Type;

/** \} */

/**
 * \struct SVM_DutyCycle_Type
 * \brief Duty cycles for three phases (as Q31 values in [0, Q31_ONE])
 *
 * Q31_ONE (0x7FFFFFFF) represents 100% duty cycle
 * Q31_ZERO (0x00000000) represents 0% duty cycle
 *
 * The duty cycles represent the "on" time for the high-side switches
 * in each phase, normalized to the switching period.
 */
typedef struct
{
    MatrixElement ta;       /**< Duty cycle for phase A (Q31 format, 0 to Q31_ONE) */
    MatrixElement tb;       /**< Duty cycle for phase B (Q31 format, 0 to Q31_ONE) */
    MatrixElement tc;       /**< Duty cycle for phase C (Q31 format, 0 to Q31_ONE) */
    SVM_Sector_Type sector; /**< Sector number for information */
} SVM_DutyCycle_Type;


