/**
 * \brief Calculate SVM duty cycles from modulation index and angle
 *
 * This function implements Space Vector Modulation according to Table 9.3
 * and generates duty cycles for symmetric switching (T0 = T7).
 *
 * \param[in]  modulation_index  Modulation index m' (0.0 to 1.0, float)
 * \param[in]  angle_rad         Angle ω·t in radians (0 to 2π, float)
 * \param[out] duty              Pointer to structure to store duty cycles
 * \return MatrixStatus_Type (MATRIX_SUCCESS on success, error code otherwise)
 */
extern MatrixStatus_Type SVM_CalculateDutyCycle(
    const MatrixFloat modulation_index,
    const MatrixFloat angle_rad,
    SVM_DutyCycle_Type * const duty);

/**
 * \brief Calculate SVM sector from dq voltage components
 *
 * Determines the sector based on the dq voltage vector components
 * according to the conditions in the text.
 *
 * \param[in]  vd     d-axis voltage (Q31 format, range [-Q31_ONE, Q31_ONE])
 * \param[in]  vq     q-axis voltage (Q31 format, range [-Q31_ONE, Q31_ONE])
 * \param[out] sector Pointer to store the sector
 * \return MatrixStatus_Type (MATRIX_SUCCESS on success, error code otherwise)
 */
extern MatrixStatus_Type SVM_GetSectorFromDQ(
    const MatrixElement vd,
    const MatrixElement vq,
    SVM_Sector_Type * const sector);

/**
 * \brief Convert duty cycles to PWM compare values
 *
 * Converts the normalized duty cycles to timer compare values
 * for center-aligned PWM generation.
 *
 * \param[in]  duty         Duty cycle structure (Q31 format)
 * \param[in]  timer_period Timer period in ticks (must be > 0)
 * \param[out] compare_a    Compare value for phase A (0 to timer_period)
 * \param[out] compare_b    Compare value for phase B (0 to timer_period)
 * \param[out] compare_c    Compare value for phase C (0 to timer_period)
 * \return MatrixStatus_Type (MATRIX_SUCCESS on success, error code otherwise)
 */
extern MatrixStatus_Type SVM_GetCompareValues(
    const SVM_DutyCycle_Type * const duty,
    const uint32_T timer_period,
    uint32_T * const compare_a,
    uint32_T * const compare_b,
    uint32_T * const compare_c);

/**
 * \brief Get phase duty cycles as floating-point values
 *
 * Utility function to convert the Q31 duty cycles back to float
 * for monitoring or debugging purposes.
 *
 * \param[in]  duty Duty cycle structure (Q31 format)
 * \param[out] ta   Phase A duty cycle as float [0.0, 1.0]
 * \param[out] tb   Phase B duty cycle as float [0.0, 1.0]
 * \param[out] tc   Phase C duty cycle as float [0.0, 1.0]
 */
extern void SVM_GetDutyCyclesFloat(
    const SVM_DutyCycle_Type * const duty,
    MatrixFloat * const ta,
    MatrixFloat * const tb,
    MatrixFloat * const tc);


