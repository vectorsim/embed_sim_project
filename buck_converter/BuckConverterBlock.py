"""
BuckConverterBlock.py
=====================

PURPOSE
-------
Auto-generated FMU wrapper for the BuckConverter Modelica plant model.
This file bridges the Modelica physics model (compiled to a binary FMU)
and the EmbedSim block-diagram simulation framework.

You typically do not edit this file by hand.  It is regenerated by:
    python buck_converter/modelica/gen_fmu.py
whenever BuckConverter.mo changes.

WHAT IS AN FMU?
---------------
A Functional Mock-up Unit (FMU) is a standardised binary container
(zip file with a shared library) defined by the FMI 2.0 standard.
OpenModelica compiles BuckConverter.mo → BuckConverter.fmu.
FMPy drives the FMU at runtime, feeding inputs and reading outputs
via the FMI C API.  EmbedSim wraps FMPy in the FMUBlock base class.

PLANT PHYSICS — AVERAGED BUCK CONVERTER MODEL
----------------------------------------------
The FMU implements the averaged (non-switching) continuous-time model
of a synchronous buck (step-down) DC-DC converter.  "Averaged" means
the high-frequency switching is replaced by a continuous duty-cycle
input d ∈ [0, 1].  This is standard practice for control design.

State equations (from BuckConverter.mo):

    L · dI_L/dt   = d · V_in - V_out       … (1) inductor dynamics
    C · dV_out/dt = I_L - V_out / R_load   … (2) capacitor / output dynamics
    I_load        = V_out / R_load          … (3) Ohm's law (algebraic)

  Physical interpretation:
    (1): The inductor voltage (d·V_in - V_out) drives current into the
         inductor.  The duty cycle d modulates how much of V_in appears
         across L.  Higher d → more volt-seconds → faster I_L rise.
    (2): I_L charges the output capacitor.  The load draws I_load.
         When I_L > I_load, V_out rises.  When I_L < I_load, V_out falls.
    (3): The load is purely resistive at R_load Ω.

  This is a 2nd-order linear time-invariant (LTI) system in (I_L, V_out).
  Its open-loop transfer function V_out(s)/D(s) has:
    natural frequency  ω_n = 1/√(LC) ≈ 10,000 rad/s  (1.6 kHz)
    damping ratio      ζ   = 1/(2·R_load) · √(L/C)  ≈ 0.05  (lightly damped)
  A PI controller is essential to stabilise and regulate this plant.

PARAMETER MEANING (DEFAULT_PARAMS)
------------------------------------
Each parameter corresponds directly to a physical component:

    L      = 100 µH   Inductor value.
                      Larger L → slower I_L slew rate → easier to filter
                      but sluggish current response.
                      Smaller L → faster response but higher current ripple.

    C      = 100 µF   Output capacitor value.
                      Larger C → lower V_out ripple and smoother regulation
                      but slower transient response to load changes.
                      Smaller C → faster response but more ripple.

    R_load = 10 Ω     Load resistance.  At V_out = 12 V:
                         I_load = 12 / 10 = 1.2 A    (nominal)
                         P_load = 12² / 10 = 14.4 W  (nominal power)
                      In Mode 2, R_load is varied (e.g., 5 Ω → 2.4 A, 28.8 W)
                      to test controller robustness to load steps.

    V_in   = 24 V     Input supply voltage.
                      Sets the duty cycle required for regulation:
                         d_ss = V_out / V_in = 12 / 24 = 0.50 (50%)
                      This is also the gain from d to V_out in steady state.

    f_sw   = 100 kHz  Switching frequency.
                      In this averaged model, f_sw does not affect the ODEs
                      (there is no explicit switching).  It is retained as a
                      parameter for documentation purposes and for any future
                      ripple-analysis extension of the model.

INPUT / OUTPUT SPECIFICATION
------------------------------
    INPUT_VARS  = ['duty']
        Duty cycle d ∈ [0, 1].  This is the control signal from the PI
        controller.  The FMU sets V_switch_avg = d × V_in internally.

    OUTPUT_VARS = ['V_out', 'I_L', 'I_load']
        V_out  : Output voltage [V] — the regulated quantity.
                 Feedback to the PI controller (via ScalarDelay).
        I_L    : Inductor current [A] — an observable state.
                 Useful for over-current detection on real hardware.
        I_load : Load current [A] = V_out / R_load.
                 Algebraic output; equals I_L in steady state.

CLASS HIERARCHY
---------------
    object
      └── VectorBlock         (wiring, signals, topology registry)
            └── FMUBlock      (FMPy integration, FMI 2.0 API)
                  └── BuckConverterBlock   ← THIS CLASS

FMUBlock handles all FMPy calls (fmu.instantiate, fmu.initialize,
fmu.doStep, fmu.terminate).  BuckConverterBlock only declares the
names and default parameters specific to this plant.

EDUCATIONAL NOTE — PARAMETER PATCHING
----------------------------------------
DEFAULT_PARAMS is a mutable class-level dictionary.  EmbedSim's
AI prober (Mode 2) patches it directly:

    BuckConverterBlock.DEFAULT_PARAMS['R_load'] = 5.0
    block = BuckConverterBlock(name=..., fmu_path=...)

This is intentional.  It follows the PMSM pattern used across EmbedSim:
plant parameters belong to the class, not to constructor arguments, so
automated parameter sweeps (e.g., over R_load, V_in) can create many
FMU instances without modifying any function signatures.

After the sweep, restore the original:
    BuckConverterBlock.DEFAULT_PARAMS.update(_DEFAULT_PARAMS_ORIG)
"""

from __future__ import annotations
import sys
from typing import Dict, List
from _path_utils import get_embedsim_import_path

# Ensure EmbedSim is discoverable BEFORE importing FMUBlock.
# _path_utils.get_embedsim_import_path() returns the project root so that
# "from embedsim.fmu_blocks import FMUBlock" resolves correctly regardless
# of the current working directory or Python sys.prefix.
sys.path.insert(0, get_embedsim_import_path())
from embedsim.fmu_blocks import FMUBlock


class BuckConverterBlock(FMUBlock):
    """
    EmbedSim FMUBlock wrapper for the averaged BuckConverter Modelica plant.

    This class makes the FMU appear as a standard VectorBlock in the
    simulation graph.  Wire it with the >> operator:

        pi_controller >> buck_plant       (sends duty cycle)
        buck_plant    >> feedback_delay   (receives [V_out, I_L, I_load])

    See module docstring for full physics explanation and parameter meanings.
    """

    # ── Input variable names — MUST match the FMU variable names exactly ──────
    # These are the causality=input variables declared in BuckConverter.mo.
    # FMUBlock uses these names to call fmu.setReal() each simulation step.
    INPUT_VARS: List[str] = ['duty']

    # ── Output variable names — MUST match the FMU variable names exactly ─────
    # These are the causality=output variables declared in BuckConverter.mo.
    # FMUBlock uses these names to call fmu.getReal() after each doStep().
    #   Index 0: V_out  — regulated output voltage [V]
    #   Index 1: I_L    — inductor current [A] (state variable)
    #   Index 2: I_load — load current [A] (algebraic, = V_out / R_load)
    OUTPUT_VARS: List[str] = ['V_out', 'I_L', 'I_load']

    # ── Default parameters — physical component values ─────────────────────────
    # Keys must match the Modelica parameter names in BuckConverter.mo exactly.
    # FMUBlock passes these to fmu.setReal() during initialisation.
    #
    # See module docstring for the physical meaning of each value.
    # Mode 2 (AI prober) patches this dict before each FMU instantiation
    # to sweep operating points (R_load, V_in, etc.).
    DEFAULT_PARAMS: Dict[str, float] = {
        'L':      0.0001,    # 100 µH  — inductor
        'C':      0.0001,    # 100 µF  — output capacitor
        'R_load': 10.0,      #  10 Ω   — nominal load resistance
        'V_in':   24.0,      #  24 V   — input supply voltage
        'f_sw':   100000.0,  # 100 kHz — switching frequency (averaged model)
    }

    def __init__(self, name: str, fmu_path: str) -> None:
        """
        Initialise the BuckConverter FMU block.

        Parameters
        ----------
        name : str
            Unique block identifier used in the topology printer,
            scope labels, and generated C variable names.
            Convention: short lowercase, e.g. 'buck' or 'plant'.

        fmu_path : str
            Absolute or relative path to BuckConverter.fmu.
            Use pathlib or os.path.join for cross-platform compatibility.
            Example:
                fmu_path = str(project_root / 'buck_converter' /
                               'modelica' / 'BuckConverter.fmu')

        Notes
        -----
        FMUBlock.__init__ calls:
            fmu.instantiate()    — loads the shared library
            fmu.initialize()     — applies DEFAULT_PARAMS and initial conditions
        The FMU is then ready to accept doStep() calls from EmbedSim's solver.
        """
        super().__init__(
            name=name,
            fmu_path=fmu_path,
            input_names=self.INPUT_VARS,
            output_names=self.OUTPUT_VARS,
            parameters=self.DEFAULT_PARAMS,
            instance_name=name,        # FMI instance name (must be unique per FMU)
        )
